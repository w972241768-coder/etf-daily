WIN = 20  # 动量窗口
# 索引: 动横N 对应列表下标 = (WIN - N)  ->  N=20→0, N=19→1, ..., N=6→14
def mom(code, N):
    arr = DATA[code][3]
    idx = WIN - N
    return arr[idx] if idx < len(arr) else None

def rank(N):
    """按某一动横(N) 对参与轮动的 ETF 降序, 返回有序 (code, 值) 列表"""
    items = [(c, mom(c, N)) for c in DATA if DATA[c][1] == "on"]
    items = [x for x in items if x[1] is not None]
    return sorted(items, key=lambda x: x[1], reverse=True)

def show_day(day_k, N):
    """day_k = 未来第 k 个交易日; 其 20 日水位 = 今日 动横(20-k) = 动横(N)"""
    r = rank(N)
    head, sec = r[0], r[1]
    lead = head[1] - sec[1]
    print(f"  第{day_k:02d}日 (动横{N:<2d}): 头 {head[0]} {head[1]:+6.2f}%   "
          f"次 {sec[0]} {sec[1]:+6.2f}%   领先 {lead:+.2f}pp")
    return head[0], lead

